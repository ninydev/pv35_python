import sys
import time
import math

# Увеличиваем лимит рекурсии (максимальное количество помощников)
# По умолчанию Python разрешает только 1000 "вложенных" вызовов
sys.setrecursionlimit(15000)


def calculate_pi_recursive(step=0, precision=0.001):
    """
    Рекурсивная функция для вычисления числа Пи по ряду Лейбница.
    Возвращает кортеж: (вычисленное_значение, количество_шагов)
    """

    # 1. Вычисляем текущий "черпак" воды по формуле: 4 * (-1)^step / (2*step + 1)
    # Знак будет чередоваться: 4, -1.33, +0.8, -0.57 и т.д.
    current_scoop = 4 * ((-1) ** step) / (2 * step + 1)

    # 2. БАЗОВЫЙ СЛУЧАЙ (Условие выхода)
    # Если размер черпака стал меньше нашей требуемой погрешности - останавливаемся!
    if abs(current_scoop) < precision:
        return current_scoop, 1  # Возвращаем последнюю каплю и 1 (считаем себя)

    # 3. РЕКУРСИВНЫЙ ВЫЗОВ
    # Если черпак еще большой, зовем следующего помощника (step + 1)
    next_sum, helpers_count = calculate_pi_recursive(step + 1, precision)

    # 4. ВОЗВРАТ РЕЗУЛЬТАТА НАВЕРХ
    # Собираем общее количество воды (моя капля + всё, что сделали остальные)
    # И считаем общее количество людей в цепочке (я + остальные)
    total_pi = current_scoop + next_sum
    total_helpers = helpers_count + 1

    return total_pi, total_helpers


# ==========================================
# ЗАПУСК И СБОР СТАТИСТИКИ
# ==========================================

print("Начинаем вычисление числа Пи через рекурсию...\n")

# Задаем точность (чем меньше число, тем больше глубина рекурсии)
TARGET_PRECISION = 0.0002

start_time = time.time()

# Вызываем нашу рекурсию. step по умолчанию равен 0.
my_pi, total_depth = calculate_pi_recursive(step=0, precision=TARGET_PRECISION)

end_time = time.time()

# Выводим красивую статистику
print("-" * 40)
print("📊 СТАТИСТИКА ВЫПОЛНЕНИЯ:")
print("-" * 40)
print(f"Требуемая точность: {TARGET_PRECISION}")
print(f"Эталонное число Пи: {math.pi}")
print(f"Наше число Пи:      {my_pi}")
print(f"Погрешность:        {abs(math.pi - my_pi):.6f}")
print("-" * 40)
print(f"Глубина рекурсии (кол-во помощников): {total_depth} вызовов")
print(f"Время выполнения программы:           {end_time - start_time:.4f} секунд")
print("-" * 40)